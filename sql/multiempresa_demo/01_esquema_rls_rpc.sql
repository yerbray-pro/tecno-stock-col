-- TecnoStock multiempresa: laboratorio AISLADO, NO ejecutar en producción.
-- Requiere Supabase de pruebas y dos usuarios registrados en auth.users.
-- Este laboratorio comprueba RLS y RPC de inventario; NO reemplaza todavía el sistema completo.
begin;

create table if not exists public.ts_demo_empresas (
  id uuid primary key default gen_random_uuid(),
  nombre text not null check (length(btrim(nombre)) between 2 and 120),
  activa boolean not null default true,
  creada_en timestamptz not null default now()
);

create table if not exists public.ts_demo_miembros (
  empresa_id uuid not null references public.ts_demo_empresas(id) on delete restrict,
  usuario_id uuid not null references auth.users(id) on delete restrict,
  rol text not null check (rol in ('admin','trabajador')),
  activo boolean not null default true,
  primary key (empresa_id, usuario_id)
);
create index if not exists ts_demo_miembros_usuario_idx on public.ts_demo_miembros (usuario_id, empresa_id);

create table if not exists public.ts_demo_productos (
  id bigint generated by default as identity primary key,
  empresa_id uuid not null references public.ts_demo_empresas(id) on delete restrict,
  codigo text not null check(length(btrim(codigo)) between 1 and 48),
  nombre text not null check(length(btrim(nombre)) between 2 and 120),
  stock integer not null default 0 check (stock >= 0),
  stock_minimo integer not null default 0 check (stock_minimo >= 0),
  activo boolean not null default true,
  unique (empresa_id, codigo),
  unique (empresa_id, id)
);
create index if not exists ts_demo_productos_empresa_idx on public.ts_demo_productos (empresa_id);

create table if not exists public.ts_demo_movimientos (
  id bigint generated by default as identity primary key,
  empresa_id uuid not null references public.ts_demo_empresas(id) on delete restrict,
  producto_id bigint not null,
  tipo text not null check (tipo in ('entrada','salida')),
  cantidad integer not null check (cantidad > 0),
  responsable_id uuid not null references auth.users(id) on delete restrict,
  motivo text,
  creado_en timestamptz not null default now(),
  foreign key (empresa_id, producto_id)
    references public.ts_demo_productos(empresa_id, id) on delete restrict
);
create index if not exists ts_demo_mov_empresa_idx on public.ts_demo_movimientos (empresa_id, creado_en desc);

-- Nadie anónimo puede leer ni modificar datos. Membresía activa determina acceso.
alter table public.ts_demo_empresas enable row level security;
alter table public.ts_demo_miembros enable row level security;
alter table public.ts_demo_productos enable row level security;
alter table public.ts_demo_movimientos enable row level security;

drop policy if exists ts_demo_empresas_select on public.ts_demo_empresas;
create policy ts_demo_empresas_select on public.ts_demo_empresas
for select to authenticated using (
  exists (select 1 from public.ts_demo_miembros m
    where m.empresa_id = id and m.usuario_id = (select auth.uid()) and m.activo)
);

drop policy if exists ts_demo_miembros_select on public.ts_demo_miembros;
create policy ts_demo_miembros_select on public.ts_demo_miembros
for select to authenticated using (usuario_id = (select auth.uid()));

drop policy if exists ts_demo_productos_select on public.ts_demo_productos;
create policy ts_demo_productos_select on public.ts_demo_productos
for select to authenticated using (
  exists (select 1 from public.ts_demo_miembros m
    where m.empresa_id = ts_demo_productos.empresa_id
      and m.usuario_id = (select auth.uid()) and m.activo)
);
drop policy if exists ts_demo_productos_insert on public.ts_demo_productos;
create policy ts_demo_productos_insert on public.ts_demo_productos
for insert to authenticated with check (
  exists (select 1 from public.ts_demo_miembros m
    where m.empresa_id = ts_demo_productos.empresa_id
      and m.usuario_id = (select auth.uid()) and m.activo and m.rol = 'admin')
);
drop policy if exists ts_demo_productos_update on public.ts_demo_productos;
create policy ts_demo_productos_update on public.ts_demo_productos
for update to authenticated using (
  exists (select 1 from public.ts_demo_miembros m
    where m.empresa_id = ts_demo_productos.empresa_id
      and m.usuario_id = (select auth.uid()) and m.activo and m.rol = 'admin')
) with check (
  exists (select 1 from public.ts_demo_miembros m
    where m.empresa_id = ts_demo_productos.empresa_id
      and m.usuario_id = (select auth.uid()) and m.activo and m.rol = 'admin')
);
-- Sin DELETE de productos: el historial debe conservarse.

drop policy if exists ts_demo_movimientos_select on public.ts_demo_movimientos;
create policy ts_demo_movimientos_select on public.ts_demo_movimientos
for select to authenticated using (
  exists (select 1 from public.ts_demo_miembros m
    where m.empresa_id = ts_demo_movimientos.empresa_id
      and m.usuario_id = (select auth.uid()) and m.activo)
);
-- No existen políticas INSERT, UPDATE ni DELETE para movimientos.

-- Los usuarios autenticados leen productos/movimientos; las operaciones se validan en el servidor.
revoke all on public.ts_demo_empresas, public.ts_demo_miembros,
  public.ts_demo_productos, public.ts_demo_movimientos from anon, authenticated;
grant usage on schema public to authenticated;
grant select on public.ts_demo_empresas, public.ts_demo_miembros,
  public.ts_demo_productos, public.ts_demo_movimientos to authenticated;
grant insert, update (codigo, nombre, stock_minimo, activo) on public.ts_demo_productos to authenticated;
grant usage, select on sequence public.ts_demo_productos_id_seq to authenticated;

-- Modificar stock únicamente a través de un RPC que usa auth.uid y verifica pertenencia.
create or replace function public.ts_demo_registrar_movimiento(
  p_empresa_id uuid,
  p_producto_id bigint,
  p_tipo text,
  p_cantidad integer,
  p_motivo text default null
) returns table (movimiento_id bigint, stock_actual integer)
language plpgsql security definer set search_path = ''
as $$
declare
  v_stock integer;
  v_nuevo integer;
  v_id bigint;
begin
  if (select auth.uid()) is null then
    raise exception 'Requiere autenticación' using errcode = '42501';
  end if;
  if not exists (
    select 1 from public.ts_demo_miembros m
    join public.ts_demo_empresas e on e.id = m.empresa_id
    where m.empresa_id = p_empresa_id and m.usuario_id = (select auth.uid())
      and m.activo and e.activa
  ) then
    raise exception 'Sin acceso a esta empresa' using errcode = '42501';
  end if;
  if p_tipo not in ('entrada','salida') or p_tipo is null
    or p_cantidad is null or p_cantidad <= 0 then
    raise exception 'Movimiento inválido' using errcode = '22023';
  end if;

  select p.stock into v_stock from public.ts_demo_productos p
    where p.empresa_id = p_empresa_id and p.id = p_producto_id and p.activo
    for update;
  if not found then
    raise exception 'Producto no disponible en esta empresa' using errcode = '42501';
  end if;
  if p_tipo = 'salida' and v_stock < p_cantidad then
    raise exception 'Stock insuficiente' using errcode = '22023';
  end if;
  if p_tipo = 'entrada' and v_stock > 2147483647 - p_cantidad then
    raise exception 'Stock excede máximo' using errcode = '22003';
  end if;

  v_nuevo := case when p_tipo = 'entrada' then v_stock + p_cantidad
                  else v_stock - p_cantidad end;
  update public.ts_demo_productos p set stock = v_nuevo
    where p.empresa_id = p_empresa_id and p.id = p_producto_id;
  insert into public.ts_demo_movimientos (
    empresa_id, producto_id, tipo, cantidad, responsable_id, motivo
  ) values (
    p_empresa_id, p_producto_id, p_tipo, p_cantidad, (select auth.uid()),
    left(coalesce(p_motivo, ''), 300)
  ) returning id into v_id;
  return query select v_id, v_nuevo;
end;
$$;
revoke all on function public.ts_demo_registrar_movimiento(uuid,bigint,text,integer,text) from public, anon;
grant execute on function public.ts_demo_registrar_movimiento(uuid,bigint,text,integer,text) to authenticated;

commit;
