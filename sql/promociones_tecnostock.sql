-- TECNOSTOCK - PROMOCIONES PROGRAMADAS
-- REVISAR ANTES DE EJECUTAR EN SUPABASE (UNICA BASE COMPARTIDA).
-- No modifica productos, precios de compra, movimientos, stock ni compras.
-- El porcentaje es una campaña informativa: NO aplica descuentos a ventas
-- porque TecnoStock todavía no tiene precio de venta / facturación.
BEGIN;

DO $$
BEGIN
  IF to_regclass('public.productos') IS NULL
     OR to_regprocedure('public.ts_es_admin()') IS NULL
     OR to_regprocedure('public.ts_puede_recibir()') IS NULL THEN
    RAISE EXCEPTION 'Primero instala productos y las funciones de compras/roles';
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.ts_promociones (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre text NOT NULL CHECK (length(btrim(nombre)) BETWEEN 3 AND 100),
  producto_id bigint NOT NULL REFERENCES public.productos(id) ON DELETE RESTRICT,
  descuento_porcentaje integer NOT NULL CHECK (descuento_porcentaje BETWEEN 1 AND 70),
  fecha_inicio date NOT NULL,
  fecha_fin date NOT NULL,
  habilitada boolean NOT NULL DEFAULT true,
  creado_por uuid NOT NULL REFERENCES auth.users(id) ON DELETE RESTRICT,
  creado_en timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ts_promos_fechas CHECK (fecha_fin >= fecha_inicio)
);
CREATE INDEX IF NOT EXISTS ts_promociones_vigencia_idx
  ON public.ts_promociones (habilitada,fecha_inicio,fecha_fin);

ALTER TABLE public.ts_promociones ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.ts_promociones FROM PUBLIC, anon, authenticated;
-- Las operaciones se hacen SOLO mediante la RPC, que valida la sesión y rol.
CREATE OR REPLACE FUNCTION public.ts_promociones(
  p_accion text,
  p_datos jsonb DEFAULT '{}'::jsonb
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE
  v_admin boolean;
  v_hoy date := (now() AT TIME ZONE 'America/Bogota')::date;
  v_nombre text;
  v_producto_id bigint;
  v_descuento integer;
  v_inicio date;
  v_fin date;
  v_id bigint;
  v_habilitada boolean;
BEGIN
  IF auth.uid() IS NULL OR NOT public.ts_puede_recibir() THEN
    RAISE EXCEPTION 'Debes iniciar sesión' USING ERRCODE = '42501';
  END IF;
  v_admin := public.ts_es_admin();
  IF p_accion = 'consultar' THEN
    RETURN coalesce((
      SELECT jsonb_agg(to_jsonb(t) ORDER BY t.fecha_inicio DESC, t.id DESC)
      FROM (
        SELECT p.id,p.nombre,p.producto_id,p.descuento_porcentaje,
               p.fecha_inicio,p.fecha_fin,p.habilitada,
               CASE
                 WHEN NOT p.habilitada THEN 'Desactivada'
                 WHEN p.fecha_fin < v_hoy THEN 'Finalizada'
                 WHEN p.fecha_inicio > v_hoy THEN 'Programada'
                 ELSE 'Activa'
               END AS estado
        FROM public.ts_promociones p
        WHERE v_admin OR
          (p.habilitada AND p.fecha_inicio <= v_hoy AND p.fecha_fin >= v_hoy)
      ) t
    ),'[]'::jsonb);
  END IF;
  IF NOT v_admin THEN
    RAISE EXCEPTION 'Solo el administrador gestiona las promociones'
      USING ERRCODE = '42501';
  END IF;
  IF p_accion = 'crear' THEN
    IF p_datos IS NULL OR jsonb_typeof(p_datos) <> 'object' THEN
      RAISE EXCEPTION 'Datos inválidos' USING ERRCODE = '22023';
    END IF;
    v_nombre := btrim(p_datos->>'nombre');
    IF char_length(v_nombre) NOT BETWEEN 3 AND 100 THEN
      RAISE EXCEPTION 'El nombre debe tener entre 3 y 100 caracteres'
        USING ERRCODE = '22023';
    END IF;
    BEGIN
      v_producto_id := (p_datos->>'producto_id')::bigint;
      v_descuento := (p_datos->>'descuento_porcentaje')::integer;
      v_inicio := (p_datos->>'fecha_inicio')::date;
      v_fin := (p_datos->>'fecha_fin')::date;
    EXCEPTION WHEN invalid_text_representation OR datetime_field_overflow THEN
      RAISE EXCEPTION 'Revisa producto, descuento y fechas' USING ERRCODE = '22023';
    END;
    IF v_producto_id IS NULL OR v_descuento IS NULL
       OR v_descuento NOT BETWEEN 1 AND 70
       OR v_inicio IS NULL OR v_fin IS NULL
       OR v_inicio > v_fin OR v_fin > v_inicio + 366 THEN
      RAISE EXCEPTION 'Descuento 1 a 70 porciento y vigencia máxima de 367 días'
        USING ERRCODE = '22023';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM public.productos
                   WHERE id = v_producto_id AND activo) THEN
      RAISE EXCEPTION 'El producto no existe o está inactivo'
        USING ERRCODE = '22023';
    END IF;
    INSERT INTO public.ts_promociones
      (nombre,producto_id,descuento_porcentaje,fecha_inicio,fecha_fin,creado_por)
    VALUES
      (v_nombre,v_producto_id,v_descuento,v_inicio,v_fin,auth.uid())
    RETURNING id INTO v_id;
    RETURN jsonb_build_object('id',v_id,'ok',true);
  END IF;
  IF p_accion = 'cambiar_estado' THEN
    BEGIN
      v_id := (p_datos->>'id')::bigint;
      v_habilitada := (p_datos->>'habilitada')::boolean;
    EXCEPTION WHEN invalid_text_representation THEN
      RAISE EXCEPTION 'Identificador o estado inválido' USING ERRCODE = '22023';
    END;
    IF v_id IS NULL OR v_habilitada IS NULL THEN
      RAISE EXCEPTION 'Indica promoción y nuevo estado' USING ERRCODE = '22023';
    END IF;
    UPDATE public.ts_promociones SET habilitada = v_habilitada WHERE id = v_id;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'Promoción no encontrada' USING ERRCODE = '22023';
    END IF;
    RETURN jsonb_build_object('ok',true,'id',v_id);
  END IF;
  RAISE EXCEPTION 'Acción no permitida' USING ERRCODE = '22023';
END;
$$;
ALTER FUNCTION public.ts_promociones(text,jsonb) OWNER TO postgres;
REVOKE ALL ON FUNCTION public.ts_promociones(text,jsonb) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.ts_promociones(text,jsonb) TO authenticated;
COMMIT;

-- Consulta de verificación. No altera ningún dato:
SELECT to_regclass('public.ts_promociones') IS NOT NULL AS tabla_promociones,
       to_regprocedure('public.ts_promociones(text,jsonb)') IS NOT NULL AS funcion_promociones;
